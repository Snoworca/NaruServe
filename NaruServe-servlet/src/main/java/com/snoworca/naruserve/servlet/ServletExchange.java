/**
 * {@link HttpExchange} over one container request and response. Request values come from the plain Servlet getters
 * (never {@code getServletPath}, {@code getPathInfo} or {@code getParameter*}); the response is written with
 * {@code setStatus}, {@code addHeader} and {@code setHeader("Content-Length")}, never {@code sendError} or
 * {@code setContentLength}, so the core owns the error body and the length. The body is read only through
 * {@code getInputStream()}, so the core parser handles multipart, urlencoded and JSON bodies; an event stream runs
 * under an {@link AsyncContext}; WebSocket and upgrade answer 501.
 */
// @req FR-SVL-002
// @req FR-SVL-003
// @req FR-SVL-004
// @req FR-SVL-005
// @req FR-SVL-007
final class ServletExchange implements HttpExchange {

    /** The largest chunk {@link #sendFile} reads and writes at once. */
    static final int CHUNK = 65536;

    /** How long abort() waits for a running drain write before completing anyway (a write blocked on the client). */
    static final long ABORT_WAIT_MILLIS = 250;

    private final HttpServletRequest req;
    private final HttpServletResponse res;
    private final String path;
    private final String method;
    private final @Nullable String query;
    private final String protocol;
    private final String remote;
    private final boolean secure;
    private final List<Map.Entry<String,String>> requestHeaders;
    private final @Nullable ServletAdapter adapter;
    // Guarded by this.
    private boolean started;
    // Guarded by this: the event-stream drain afterHandler() submits, its stream, and whether that already ran.
    private ServletEventStream.@Nullable DrainTask drainTask;
    private boolean managed;
    private boolean stopRequested;
    private boolean asyncStarting;
    private boolean aborting;
    private boolean retired;
    // Guarded by this; an owning SSE drain sees the original failure before generic abort notification.
    private @Nullable Throwable streamFailure;
    private volatile boolean finished;
    // Only responses generated by the adapter bypass the core's own access-log metrics.
    private volatile int adapterResponseStatus;
    private volatile long adapterResponseBytes = -1;
    private boolean handlerReturned;
    // Lock-free so abort() never waits for a writer.
    private volatile boolean aborted;
    // Set once an ordinary pending request or event stream starts async processing.
    private volatile @Nullable AsyncContext async;
    private final AtomicBoolean completed = new AtomicBoolean();
    private final AbortListeners abortListeners = new AbortListeners();
    private final RequestRetentions retentions = new RequestRetentions(this::completeIfReady);
    /** Held by the event stream's body stream around each write; abort() waits for it before completing. */
    final ReentrantLock writeLock = new ReentrantLock();

    /** An exchange without an adapter: no event stream can start on it. */
    // @req FR-SVL-002
    ServletExchange(HttpServletRequest req, HttpServletResponse res, String path) {
        this(req, res, path, null);
    }

    /** An exchange of {@code adapter}, whose {@link ServletAdapter#pool} counts and runs its event stream. */
    // @req FR-SVL-002
    // @req FR-SVL-005
    ServletExchange(HttpServletRequest req, HttpServletResponse res, String path, @Nullable ServletAdapter adapter) {
        this.req = req;
        this.res = res;
        this.path = path;
        this.adapter = adapter;
        // A container may reuse its request after completion; saved Next callbacks still own this immutable head.
        this.method = req.getMethod();
        this.query = req.getQueryString();
        this.protocol = req.getProtocol();
        this.remote = req.getRemoteAddr();
        this.secure = req.isSecure();
        this.requestHeaders = snapshotHeaders(req);
    }

    // @req FR-SVL-002
    @Override
    public String methodToken() {
        return method;
    }

    // @req IR-HTTP-009 AC-8; FR-APP-019 AC-3
    @Override
    public int responseStatus() {
        return adapterResponseStatus;
    }

    // @req IR-HTTP-009 AC-8; FR-APP-019 AC-3
    @Override
    public long responseBytesWritten() {
        return adapterResponseBytes;
    }

    /** The remainder {@link ServletPath} computed from the raw request URI. */
    // @req FR-SVL-002
    @Override
    public String rawPath() {
        return path;
    }

    // @req FR-SVL-002
    @Override
    public @Nullable String rawQuery() {
        return query;
    }

    // @req FR-SVL-002
    @Override
    public String httpVersion() {
        return protocol;
    }

    /** Every value of every name, in per-name order; the Servlet API gives no order across names. */
    // @req FR-SVL-002
    @Override
    public List<Map.Entry<String, String>> headers() {
        return requestHeaders;
    }

    private static List<Map.Entry<String,String>> snapshotHeaders(HttpServletRequest req) {
        List<Map.Entry<String, String>> out = new ArrayList<>();
        Set<String> seen = new HashSet<>();
        Enumeration<String> names = req.getHeaderNames();
        while (names != null && names.hasMoreElements()) {
            String name = names.nextElement();
            // Servlet getHeaders is case-insensitive even if its name enumeration contains both spellings.
            if (!seen.add(name.toLowerCase(Locale.ROOT))) continue;
            Enumeration<String> values = req.getHeaders(name);
            while (values != null && values.hasMoreElements()) {
                out.add(new SimpleImmutableEntry<>(name, values.nextElement()));
            }
        }
        return Collections.unmodifiableList(out);
    }

    /**
     * The container's input stream only: the core parser reads multipart, urlencoded and JSON bodies from it, so
     * {@code getParts}, {@code getPart} and {@code getParameter*} are never called and the core limits apply.
     */
    // @req FR-SVL-002
    // @req FR-SVL-004
    @Override
    public InputStream requestBody() {
        try {
            checkInputAvailable();
            return new FilterInputStream(req.getInputStream()) {
                @Override public int read() throws IOException {
                    checkInputAvailable();
                    try { return in.read(); } catch (IOException failure) { abort(); throw failure; }
                }
                @Override public int read(byte[] bytes, int offset, int length) throws IOException {
                    checkInputAvailable();
                    try { return in.read(bytes, offset, length); } catch (IOException failure) { abort(); throw failure; }
                }
                @Override public long skip(long length) throws IOException {
                    checkInputAvailable();
                    try { return in.skip(length); } catch (IOException failure) { abort(); throw failure; }
                }
            };
        } catch (IOException e) {
            abort();
            throw new UncheckedIOException("request body unavailable", e);
        }
    }

    // @req FR-SVL-002
    @Override
    public String remoteAddress() {
        return remote;
    }

    // @req FR-SVL-002
    @Override
    public boolean isSecure() {
        return secure;
    }

    // @req FR-APP-023 AC-8
    @Override
    public Runnable retainRequest() {
        synchronized (this) {
            if (aborted || retired || completed.get() || finished && !retentions.isRetained()) return () -> {};
            return retentions.retain();
        }
    }

    private void checkInputAvailable() throws IOException {
        synchronized (this) {
            checkNotAborted();
            if (retired || completed.get()) throw new IOException("request input already released");
        }
    }

    /** {@code contentLength} needs no action: the core's Content-Length header is passed as given. */
    // @req FR-SVL-003
    // @req FR-SVL-009 AC-1 AC-2 AC-4
    @Override
    public OutputStream commit(int status, List<Map.Entry<String, String>> headers, long contentLength)
            throws IOException {
        boolean claimed = false;
        try {
            writeLock.lock();
            try {
                synchronized (this) {
                    requireStartable();
                    started = true;
                    claimed = true;
                }
                head(status, headers);
                return new FilterOutputStream(res.getOutputStream()) {
                    @Override public void write(int b) throws IOException { writeBody(() -> out.write(b)); }
                    @Override public void write(byte[] b, int off, int len) throws IOException { writeBody(() -> out.write(b, off, len)); }
                    @Override public void flush() throws IOException { writeBody(() -> out.flush()); }
                    @Override public void close() { /* finish/AsyncContext owns response termination. */ }
                };
            } finally {
                writeLock.unlock();
            }
        } catch (IOException | RuntimeException failure) {
            // A rejected second start is validation, not a detected transport failure.
            if (claimed) abort();
            throw failure;
        }
    }

    interface IoOperation { void run() throws IOException; }

    private void writeBody(IoOperation operation) throws IOException {
        boolean attempted = false;
        try {
            writeLock.lock();
            try {
                checkWritable();
                attempted = true;
                operation.run();
            } finally {
                writeLock.unlock();
            }
        } catch (IOException | RuntimeException failure) {
            // Abort callbacks may enter the core; never notify while the transport write lock is held.
            if (attempted) abort();
            throw failure;
        }
    }

    /** Stream IO first propagates to its owning drain, which records the protocol-specific close cause. */
    void writeStreamBody(IoOperation operation) throws IOException {
        writeLock.lock();
        try {
            checkWritable();
            try {
                operation.run();
            } catch (IOException | RuntimeException failure) {
                // Record before releasing the IO lock: concurrent finish cannot convert failed IO into success.
                synchronized (this) { if (streamFailure == null) streamFailure = failure; }
                throw failure;
            }
        } finally {
            writeLock.unlock();
        }
    }

    /** Caller holds the exchange monitor. */
    private void throwStreamFailure() throws IOException {
        if (streamFailure instanceof IOException) throw (IOException) streamFailure;
        if (streamFailure instanceof RuntimeException) throw (RuntimeException) streamFailure;
    }

    // @req FR-SVL-003
    // @req FR-SVL-009 AC-1 AC-2 AC-4
    @Override
    public void finish() throws IOException {
        try {
            writeLock.lock();
            try {
                synchronized (this) {
                    checkNotAborted();
                    throwStreamFailure();
                    if (finished) return;
                }
                res.flushBuffer();
                synchronized (this) { finished = true; }
            } finally {
                writeLock.unlock();
            }
            completeIfReady();
        } catch (IOException | RuntimeException failure) {
            abort();
            throw failure;
        }
    }

    // @req IR-HTTP-009 AC-1 AC-2 AC-3
    @Override
    public void onAbort(Runnable listener) {
        abortListeners.onAbort(listener);
    }

    /** A non-async abnormal response still fails the active servlet invocation. */
    // @req FR-SVL-003
    boolean abortedWithoutStream() {
        return aborted && async == null;
    }

    /** Aborts without waiting indefinitely for a transport write; running drains keep their slot until exit. */
    // @req FR-SVL-003 FR-SVL-005
    // @req FR-SVL-009 AC-2 AC-4
    @Override
    public void abort() { abort(ABORT_WAIT_MILLIS); }

    private void abort(long waitMillis) {
        ServletEventStream.DrainTask task;
        synchronized (this) {
            if (retired || completed.get() || aborting || aborted) return;
            if (finished && !retentions.isRetained()) return;
            aborting = true;
            aborted = true;
            finished = true;
            task = drainTask;
        }
        try {
            // Core cancellation may release its retention reentrantly; defer physical completion until this abort exits.
            try {
                // An undrained core SSE client records its protocol cause before generic request cancellation.
                if (task != null) task.cancelBeforeStart();
            } finally {
                abortListeners.abort();
            }
            if (async != null) {
                boolean held = false;
                try {
                    held = writeLock.tryLock(waitMillis, TimeUnit.MILLISECONDS);
                } catch (InterruptedException e) {
                    Thread.currentThread().interrupt();
                } finally {
                    if (held) writeLock.unlock();
                }
            }
        } finally {
            synchronized (this) { aborting = false; }
            completeIfReady();
        }
    }

    /**
     * Commits, then copies {@code length} bytes from {@code offset} through java.io in chunks of {@link #CHUNK}. The
     * arguments are checked in the order of the TinyHttpd adapter: the range (IllegalArgumentException), then the
     * abort check and single-start rule, then the open of the file.
     */
    // @req FR-SVL-003
    @Override
    public void sendFile(int status, List<Map.Entry<String, String>> headers, File file, long offset, long length)
            throws IOException {
        // The range first, then the start rule, then the open (the order of the TinyHttpd adapter), so a bad range or
        // a missing file leaves the response unstarted and the core can still answer with an error.
        long size = file.length();
        if (offset < 0 || length < 0 || offset > size - length) {
            throw new IllegalArgumentException(
                    "range offset " + offset + " length " + length + " outside file of " + size + " bytes");
        }
        requireStartable();
        OutputStream out;
        try (InputStream in = new FileInputStream(file)) {
            for (long skipped = 0; skipped < offset; ) {
                long n = in.skip(offset - skipped);
                if (n <= 0) {
                    throw new EOFException("file ended before offset " + offset + ": " + file);
                }
                skipped += n;
            }
            out = commit(status, headers, length);
            byte[] buf = new byte[(int) Math.min(CHUNK, Math.max(1, length))];
            for (long left = length; left > 0; ) {
                int n = in.read(buf, 0, (int) Math.min(buf.length, left));
                if (n < 0) {
                    throw new EOFException("file ended " + left + " bytes before the requested range: " + file);
                }
                out.write(buf, 0, n);
                left -= n;
            }
        }
        out.flush();
    }

    /** Servlet 3.1 offers no upgrade the core can use here: 501, the exchange left unstarted. */
    // @req FR-SVL-003
    // @req FR-SVL-007
    @Override
    public void upgrade(List<Map.Entry<String, String>> headers, UpgradeHandler handler) {
        throw new HttpException(501, "upgrade is not supported by the Servlet adapter");
    }

    /**
     * WebSocket is not supported on the Servlet adapter in v1: 501 instead of the SPI default, which the core would
     * answer with 500; the exchange stays unstarted, so the core commits the error.
     */
    // @req FR-SVL-007
    @Override
    public void webSocket(WebSocketSettings settings, WebSocketEndpoint endpoint) {
        throw new HttpException(501, "WebSocket is not supported by the Servlet adapter");
    }

    // @req FR-SVL-003
    // @req FR-SVL-005
    @Override
    public void eventStream(int status, List<Map.Entry<String, String>> headers, StreamDrain drain)
            throws IOException {
        ServletEventStream.start(this, status, headers, drain);
    }

    /** Initial callback return is not a terminal response: retain unfinished managed requests with AsyncContext. */
    // @req FR-SVL-005
    // @req FR-SVL-009 AC-1 AC-2 AC-3 AC-4
    void afterHandler() {
        ServletEventStream.DrainTask task;
        boolean needAsync;
        synchronized (this) {
            if (handlerReturned) return;
            handlerReturned = true;
            needAsync = managed && (!finished || retentions.isRetained()) && !aborted && async == null;
            task = drainTask;
        }
        if (needAsync) {
            try {
                ensureAsync();
            } catch (IllegalStateException cannotDefer) {
                // A completed wire response can still own input; failed retention must cancel that work.
                if (!finished || retentions.isRetained()) unsupportedAsync();
            }
        }
        if (stopRequested && (!finished || retentions.isRetained())) abort();
        if (task != null) submit(task);
        retireIfDone();
    }

    private void submit(ServletEventStream.DrainTask task) {
        if (aborted) { task.cancelBeforeStart(); return; }
        try {
            pool().submit(task);
        } catch (RejectedExecutionException failure) {
            abort();
            task.cancelBeforeStart();
        }
    }

    private void unsupportedAsync() {
        try {
            if (started) { abort(); return; }
            byte[] bytes = Objects.requireNonNull(adapter).errorRenderer().render(500).getBytes(StandardCharsets.UTF_8);
            List<Map.Entry<String,String>> headers = new ArrayList<>();
            headers.add(new SimpleImmutableEntry<>("Content-Type", "application/json; charset=utf-8"));
            headers.add(new SimpleImmutableEntry<>("Content-Length", String.valueOf(bytes.length)));
            OutputStream output = commit(500, headers, bytes.length);
            adapterResponseStatus = 500;
            adapterResponseBytes = 0;
            output.write(bytes);
            adapterResponseBytes = bytes.length;
            finish();
            // FR-SVL-009 AC-4; FR-APP-023 AC-8: this adapter answer bypasses core Response.onDone.
            abort(); // revoke retained core work after the complete JSON500, without a second response
        } catch (IOException | RuntimeException failure) {
            abort();
        }
    }

    // @req FR-SVL-009 AC-2 AC-4
    synchronized void managed() { managed = true; }

    // @req FR-SVL-009 AC-4
    void stopAfterReturn() {
        boolean cut;
        synchronized (this) { stopRequested = true; cut = handlerReturned && (!finished || retentions.isRetained()); }
        // SSE aborts already run in parallel in Pool.completeAll; do not add one write wait per stream.
        if (cut && (adapter == null || adapter.pool() == null || !adapter.pool().owns(this))) abort(0);
    }

    private void retireIfDone() {
        boolean retire;
        synchronized (this) {
            retire = managed && handlerReturned && finished && !asyncStarting && !aborting && !retired
                    && (aborted || !retentions.isRetained()) && (async == null || completed.get());
            if (retire) retired = true;
        }
        if (retire && adapter != null) adapter.retire(this);
    }

    // @req FR-SVL-009 AC-1 AC-2 AC-4
    AsyncContext ensureAsync() {
        boolean managedRequest;
        synchronized (this) {
            while (asyncStarting) {
                try { wait(); }
                catch (InterruptedException failure) {
                    Thread.currentThread().interrupt();
                    throw new IllegalStateException("interrupted while starting async response", failure);
                }
            }
            if (aborted || retired || completed.get() || finished && !retentions.isRetained()) throw new IllegalStateException("exchange already ended");
            if (async != null) return async;
            if (!req.isAsyncSupported()) throw new IllegalStateException("deferred response needs asyncSupported=true");
            asyncStarting = true;
            managedRequest = managed;
        }
        AsyncContext context = null;
        try {
            // Container calls and listener callbacks do not execute under the exchange monitor.
            context = req.isAsyncStarted() ? req.getAsyncContext() : req.startAsync();
            if (managedRequest) context.addListener(new AsyncListener() {
                @Override public void onComplete(AsyncEvent event) {
                    completed.set(true);
                    synchronized (ServletExchange.this) { finished = true; }
                    retireIfDone();
                }
                @Override public void onTimeout(AsyncEvent event) { abort(); }
                @Override public void onError(AsyncEvent event) { abort(); }
                @Override public void onStartAsync(AsyncEvent event) { event.getAsyncContext().addListener(this); }
            });
            boolean ended;
            synchronized (this) { async = context; ended = aborted || finished && !retentions.isRetained(); }
            if (ended) {
                complete();
                throw new IllegalStateException("exchange ended while starting async response");
            }
            return context;
        } catch (RuntimeException failure) {
            if (context != null) {
                synchronized (this) { async = context; }
                abort();
            }
            throw failure;
        } finally {
            synchronized (this) { asyncStarting = false; notifyAll(); }
            completeIfReady();
        }
    }

    /** The pool of the adapter; IllegalStateException for an exchange without one. */
    // @req FR-SVL-005
    ServletEventStream.Pool pool() {
        ServletEventStream.Pool p = adapter != null ? adapter.pool() : null;
        if (p == null) {
            throw new IllegalStateException("no SSE pool: the exchange has no bound ServletAdapter");
        }
        return p;
    }

    HttpServletRequest request() {
        return req;
    }

    HttpServletResponse response() {
        return res;
    }

    /** Closed exchanges cannot be promoted; a managed pending ordinary request may become an event stream. */
    // @req FR-SVL-005 FR-SVL-009 AC-3
    synchronized void requireDrainable() {
        if (handlerReturned && !managed) {
            throw new IllegalStateException("eventStream must be called before the unmanaged handler returns");
        }
    }

    // @req FR-SVL-005
    synchronized void markStarted() { started = true; }

    // @req FR-SVL-005
    void async(AsyncContext ac) { async = ac; }

    /** Claim a drain once; late registration submits to the same bounded SSE executor immediately. */
    // @req FR-SVL-005 FR-SVL-009 AC-3
    void register(StreamDrain drain, OutputStream out) {
        ServletEventStream.DrainTask task = new ServletEventStream.DrainTask(this, drain, out);
        boolean late;
        synchronized (this) {
            requireDrainable();
            drainTask = task;
            late = handlerReturned;
        }
        if (late) submit(task);
    }

    /** Mark terminal and complete any started AsyncContext once, then release only an admitted returned request. */
    // @req FR-SVL-005 FR-SVL-009 AC-2 AC-4
    void complete() {
        boolean failed;
        synchronized (this) {
            failed = !aborted && streamFailure != null;
            if (!failed) finished = true;
        }
        // A custom drain may catch IO and return normally; ownership exit still observes terminal failure.
        if (failed) { abort(); return; }
        completeIfReady();
    }

    /** Completion invokes container listeners, so neither exchange nor IO monitors are held around it. */
    private void completeIfReady() {
        AsyncContext ac;
        boolean finishContext;
        synchronized (this) {
            if (!finished || asyncStarting || aborting || !aborted && retentions.isRetained()) return;
            ac = async;
            finishContext = ac != null && completed.compareAndSet(false, true);
        }
        if (finishContext) {
            try {
                ac.complete();
            } catch (IllegalStateException ignored) {
                // The container has already ended the request.
            }
        }
        retireIfDone();
    }

    /** Status and headers: Content-Length through setHeader, every other header through addHeader, in order. */
    // @req FR-SVL-003
    void head(int status, List<Map.Entry<String, String>> headers) {
        res.setStatus(status);
        for (Map.Entry<String, String> h : headers) {
            if (h.getKey().equalsIgnoreCase("Content-Length")) {
                res.setHeader(h.getKey(), h.getValue());
            } else {
                res.addHeader(h.getKey(), h.getValue());
            }
        }
    }

    void checkNotAborted() throws IOException {
        if (aborted) {
            throw new IOException("exchange aborted");
        }
    }

    /** Input retention never permits another output write after logical response completion. */
    synchronized void checkWritable() throws IOException {
        checkNotAborted();
        if (finished) throw new IOException("exchange finished");
    }

    /** A second start of one exchange throws IllegalStateException; an aborted one throws IOException. */
    // @req FR-SVL-003
    synchronized void requireStartable() throws IOException {
        checkNotAborted();
        if (finished) throw new IOException("exchange finished");
        if (started) {
            throw new IllegalStateException("the response was already started");
        }
    }
}
